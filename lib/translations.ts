export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let str = translations[lang]?.[key] ?? translations.uz[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}
